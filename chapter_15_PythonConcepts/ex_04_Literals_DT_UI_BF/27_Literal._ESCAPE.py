# 27_Literal._ESCAPE.py
# Demonstrates escape sequences inside strings: \n (new line), \t (tab) and
# \b (backspace), showing how they change the printed output.
# Escape Sequence
# \n -> new line
# \t -> tab
# \b -> backspace (1 char backspace)

print("Hello\nWorld")
print("Hello\tWorld")
print("Hello\bWorld")