# Notes that Python has no ++ / -- operators; instead it uses augmented
# assignment (+=, -=, *=) to update a variable in place.
# Increment (++) / Decrement (--) Operators
# Good news - Doesn't have ++, -- operator

x = 5
x += 1
print(x)

x -= 1  # x= x-1
print(x)

x *= 3  # x= x*1
print(x)